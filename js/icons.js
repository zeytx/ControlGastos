export function icon(name, { size = 22, className = '' } = {}) {
  const path = PATHS[name] || '';
  return `<svg class="svg-icon ${className}" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.9" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${path}</svg>`;
}

/** Pinta los iconos declarados en el HTML con data-icon="nombre". */
export function hydrateIcons(root = document) {
  root.querySelectorAll('[data-icon]').forEach((element) => {
    if (element.dataset.iconReady) return;
    element.innerHTML = icon(element.dataset.icon, { size: Number(element.dataset.iconSize) || 22 });
    element.dataset.iconReady = '1';
  });
}

